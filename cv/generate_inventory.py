#!/usr/bin/env python3
"""Build inventory.yaml from a folder of inspection photos. No cropping.

Duplicates are sha256 (not the model). Each unique image is labelled by a
vision model (xAI grok-4.6) into the taxonomy in taxonomy.py.

    export XAI_API_KEY=...
    python cv/generate_inventory.py fixtures/fleet-vehicle-return/images \\
        --out /tmp/inventory.yaml
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import mimetypes
import os
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from taxonomy import DEPICTS, HEADLINER_SHOT_FROM, LABEL_GUIDE

IMAGE_EXT = {".jpg", ".jpeg", ".png"}
MODEL = os.environ.get("CV_MODEL", "grok-4.6")
API_BASE = os.environ.get("XAI_BASE_URL", "https://api.x.ai/v1")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def list_images(folder: Path) -> list[Path]:
    files = [p for p in folder.iterdir() if p.suffix.lower() in IMAGE_EXT and p.is_file()]
    return sorted(files, key=lambda p: p.name)


def collapse_duplicates(paths: list[Path]) -> tuple[list[Path], list[list[str]]]:
    by_hash: dict[str, list[Path]] = defaultdict(list)
    for p in paths:
        by_hash[sha256_file(p)].append(p)
    unique: list[Path] = []
    pairs: list[list[str]] = []
    for group in by_hash.values():
        group = sorted(group, key=lambda p: p.name)
        unique.append(group[0])
        if len(group) > 1:
            for extra in group[1:]:
                pairs.append([group[0].name, extra.name])
    unique.sort(key=lambda p: p.name)
    return unique, pairs


def dump_yaml(images: list[dict], pairs: list[list[str]]) -> str:
    lines = [
        "# Generated by cv/generate_inventory.py — vision labels, sha256 dedupe.",
        "# Cropping is out of scope.",
        "",
        "images:",
    ]
    for img in images:
        lines.append(f'  - file: "{img["file"]}"')
        lines.append(f"    depicts: {img['depicts']}")
        if img.get("shot_from"):
            lines.append(f"    shot_from: {img['shot_from']}")
        if img.get("note"):
            note = img["note"].replace("\n", " ").strip()
            lines.append(f"    note: {json.dumps(note, ensure_ascii=False)}")
        if img.get("exact_duplicate_of"):
            lines.append(f'    exact_duplicate_of: "{img["exact_duplicate_of"]}"')
    lines.append("")
    lines.append("exact_duplicate_pairs:")
    if not pairs:
        lines.append("  []")
    else:
        for a, b in pairs:
            lines.append(f'  - ["{a}", "{b}"]')
    lines.append("")
    return "\n".join(lines)


def label_image(client, path: Path) -> dict:
    mime = mimetypes.guess_type(path.name)[0] or "image/jpeg"
    b64 = base64.b64encode(path.read_bytes()).decode("ascii")
    data_url = f"data:{mime};base64,{b64}"
    prompt = f"""You label vehicle-return inspection photos.

Choose exactly one depicts value:
{", ".join(DEPICTS)}

{LABEL_GUIDE}

Return ONLY JSON, no markdown:
{{"depicts": "<one of the values>", "shot_from": null or "between_front_seats" or "beside_seat", "note": "<short English note>"}}

shot_from must be set if and only if depicts is headliner.
shot_from allowed: {", ".join(HEADLINER_SHOT_FROM)}
"""
    response = client.responses.create(
        model=MODEL,
        input=[
            {
                "role": "user",
                "content": [
                    {"type": "input_image", "image_url": data_url, "detail": "high"},
                    {"type": "input_text", "text": prompt},
                ],
            }
        ],
    )
    text = response.output_text.strip()
    if text.startswith("```"):
        text = text.strip("`")
        text = text.removeprefix("json").strip()
    data = json.loads(text)
    depicts = data.get("depicts")
    if depicts not in DEPICTS:
        raise ValueError(f"{path.name}: unknown depicts {depicts!r} raw={text[:200]!r}")
    shot = data.get("shot_from") or None
    if depicts == "headliner":
        if shot not in HEADLINER_SHOT_FROM:
            raise ValueError(f"{path.name}: headliner missing shot_from, got {shot!r}")
    else:
        shot = None
    return {
        "file": path.name,
        "depicts": depicts,
        "shot_from": shot,
        "note": (data.get("note") or "").strip(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("images", type=Path, help="folder of jpg/png")
    parser.add_argument("--out", type=Path, default=Path("inventory.generated.yaml"))
    args = parser.parse_args()

    key = os.environ.get("XAI_API_KEY")
    if not key:
        print("XAI_API_KEY is not set", file=sys.stderr)
        return 2

    from openai import OpenAI

    client = OpenAI(api_key=key, base_url=API_BASE)

    folder = args.images.resolve()
    all_files = list_images(folder)
    if not all_files:
        print(f"no images in {folder}", file=sys.stderr)
        return 2

    unique, pairs = collapse_duplicates(all_files)
    print(f"{len(all_files)} files, {len(unique)} unique, {len(pairs)} duplicate extras", flush=True)

    labelled: list[dict] = []
    for path in unique:
        print(f"label {path.name} ...", flush=True)
        row = label_image(client, path)
        extras = [b for a, b in pairs if a == path.name]
        if extras:
            row["exact_duplicate_of"] = extras[0]
        labelled.append(row)

    # Keep unique rows only (same as golden inventory.yaml).
    text = dump_yaml(labelled, pairs)
    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
